/**
 * Helper to get localized UI string
 */
export function t(key, lang = 'en') {
  const dictionary = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.en;
  return dictionary[key] || UI_TRANSLATIONS.en[key] || key;
}

/**
 * Returns localized question object with Amharic fallback
 */
export function getLocalizedQuestion(question, lang = 'en') {
  if (!question) return question;
  if (lang === 'am') {
    const qAm = question.question_am && question.question_am.trim() ? question.question_am : question.question;
    const optsAm = (question.options_am && Array.isArray(question.options_am) && question.options_am.length === question.options.length)
      ? question.options_am
      : question.options;
    
    const bookAm = BIBLE_BOOKS_AMHARIC[question.book] || question.book;
    const categoryAm = CATEGORIES_AMHARIC[question.category] || question.category;
    const testamentAm = TESTAMENTS_AMHARIC[question.testament] || question.testament;
    const difficultyAm = DIFFICULTIES_AMHARIC[question.difficulty] || question.difficulty;

    return {
      ...question,
      question: qAm,
      options: optsAm,
      book: bookAm,
      category: categoryAm,
      testament: testamentAm,
      difficulty: difficultyAm
    };
  }
  return question;
}
